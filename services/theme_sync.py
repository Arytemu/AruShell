#!/usr/bin/env python3
"""
AruShell Dynamic System Theme Sync (Kitty + GTK3/GTK4 accents).
Called automatically when Material You palette changes (if ShellConfig.syncSystemTheme is enabled).
Usage: theme_sync.py <primary_hex> <on_primary_hex> <surface_hex>
"""

import os
import re
import subprocess
import sys


HOME = os.path.expanduser("~")


def norm_hex(s: str, fallback: str) -> str:
    s = (s or "").strip().lstrip("#")
    if re.fullmatch(r"[0-9a-fA-F]{6}", s):
        return "#" + s.lower()
    return fallback


def sync_gtk(primary: str, on_primary: str) -> None:
    block = f"""
/* AruShell Dynamic Accent */
@define-color accent_bg_color {primary};
@define-color accent_fg_color {on_primary};
@define-color accent_color {primary};
/* end AruShell Dynamic Accent */
"""
    for ver in ("gtk-3.0", "gtk-4.0"):
        d = os.path.join(HOME, ".config", ver)
        p = os.path.join(d, "gtk.css")
        os.makedirs(d, exist_ok=True)
        txt = open(p, encoding="utf-8").read() if os.path.isfile(p) else ""
        txt = re.sub(
            r"\n?/\* AruShell Dynamic Accent \*/.*?/\* end AruShell Dynamic Accent \*/\n?",
            "\n",
            txt,
            flags=re.S,
        )
        open(p, "w", encoding="utf-8").write(txt.rstrip() + "\n" + block.lstrip("\n"))


def sync_kitty(primary: str, on_primary: str) -> None:
    kitty_dir = os.path.join(HOME, ".config", "kitty")
    kitty_conf = os.path.join(kitty_dir, "kitty.conf")
    if not os.path.isfile(kitty_conf):
        return

    accent_file = os.path.join(kitty_dir, "arushell_accent.conf")
    content = (
        "# Auto-generated by AruShell Dynamic Theme Sync\n"
        f"cursor                  {primary}\n"
        f"url_color               {primary}\n"
        f"active_border_color     {primary}\n"
        f"active_tab_background   {primary}\n"
        f"active_tab_foreground   {on_primary}\n"
        f"selection_background    {primary}\n"
        f"selection_foreground    {on_primary}\n"
        f"color4                  {primary}\n"
        f"color12                 {primary}\n"
    )
    with open(accent_file, "w", encoding="utf-8") as f:
        f.write(content)

    # Ensure kitty.conf includes arushell_accent.conf at the end
    conf_txt = open(kitty_conf, encoding="utf-8").read()
    inc_line = "include arushell_accent.conf"
    if inc_line not in conf_txt:
        with open(kitty_conf, "w", encoding="utf-8") as f:
            f.write(conf_txt.rstrip() + "\n\n# AruShell Dynamic Accent\n" + inc_line + "\n")

    subprocess.run(["pkill", "-USR1", "kitty"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)



def reset_all() -> None:
    # Remove GTK dynamic accent block
    for ver in ("gtk-3.0", "gtk-4.0"):
        p = os.path.join(HOME, ".config", ver, "gtk.css")
        if os.path.isfile(p):
            txt = open(p, encoding="utf-8").read()
            txt = re.sub(
                r"\n?/\* AruShell Dynamic Accent \*/.*?/\* end AruShell Dynamic Accent \*/\n?",
                "\n",
                txt,
                flags=re.S,
            )
            open(p, "w", encoding="utf-8").write(txt.rstrip() + "\n")
    # Remove Kitty accent file & include line
    kitty_dir = os.path.join(HOME, ".config", "kitty")
    accent_file = os.path.join(kitty_dir, "arushell_accent.conf")
    if os.path.isfile(accent_file):
        try:
            os.remove(accent_file)
        except Exception:
            pass
    kitty_conf = os.path.join(kitty_dir, "kitty.conf")
    if os.path.isfile(kitty_conf):
        conf_txt = open(kitty_conf, encoding="utf-8").read()
        conf_txt = re.sub(r"\n?# AruShell Dynamic Accent\ninclude arushell_accent\.conf\n?", "\n", conf_txt)
        conf_txt = conf_txt.replace("include arushell_accent.conf", "")
        open(kitty_conf, "w", encoding="utf-8").write(conf_txt.rstrip() + "\n")
        subprocess.run(["pkill", "-USR1", "kitty"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def main() -> int:
    if len(sys.argv) >= 2 and sys.argv[1] == "reset":
        reset_all()
        return 0
    if len(sys.argv) < 3:
        return 1
    primary = norm_hex(sys.argv[1], "#d0bcff")
    on_primary = norm_hex(sys.argv[2], "#211f26")
    sync_gtk(primary, on_primary)
    sync_kitty(primary, on_primary)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
