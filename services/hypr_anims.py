#!/usr/bin/env python3
"""
AruShell Hyprland Animation Customizer.
Usage: hypr_anims.py <preset> [win_style] [ws_style] [speed_mult]
  preset:    smooth | snappy | bounce | minimal | off
  win_style: popin | slide | gnomed | fade
  ws_style:  slide | slidefade | fade | slidevert
  speed:     0.6 .. 1.6 (lower = faster)
"""

import glob
import os
import subprocess
import sys


HOME = os.path.expanduser("~")
ANIM_LUA = os.path.join(HOME, ".config", "hypr", "arushell_anims.lua")


def find_hypr_sig() -> str:
    sig = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE", "").strip()
    uid = os.getuid()
    base = f"/run/user/{uid}/hypr"
    if sig and os.path.exists(os.path.join(base, sig, ".socket.sock")):
        return sig
    if os.path.isdir(base):
        socks = glob.glob(os.path.join(base, "*", ".socket.sock"))
        if socks:
            socks.sort(key=lambda p: os.path.getmtime(p), reverse=True)
            return os.path.basename(os.path.dirname(socks[0]))
    return ""


CURVES = {
    "smooth":  ("m3smooth, 0.22, 1.0, 0.36, 1.0",  4.2, 3.5, 3.8, 4.0, 3.2),
    "snappy":  ("m3snappy, 0.12, 1.0, 0.24, 1.0",  2.4, 2.0, 2.2, 2.4, 2.0),
    "bounce":  ("m3bounce, 0.16, 1.12, 0.28, 1.0", 4.6, 3.6, 3.5, 4.4, 3.4),
    "minimal": ("m3fast, 0.2, 1.0, 0.3, 1.0",      1.4, 1.2, 1.4, 1.6, 1.2),
}


def main() -> int:
    preset = (sys.argv[1] if len(sys.argv) > 1 else "smooth").strip().lower()
    win_style = (sys.argv[2] if len(sys.argv) > 2 else "popin").strip().lower()
    ws_style = (sys.argv[3] if len(sys.argv) > 3 else "slide").strip().lower()
    try:
        speed = max(0.4, min(2.5, float(sys.argv[4]))) if len(sys.argv) > 4 else 1.0
    except Exception:
        speed = 1.0

    if win_style not in ("popin", "slide", "gnomed", "fade"):
        win_style = "popin"
    if ws_style not in ("slide", "slidefade", "fade", "slidevert"):
        ws_style = "slide"

    win_in_arg = "popin 86%" if win_style == "popin" else win_style
    win_out_arg = "popin 88%" if win_style == "popin" else win_style

    if preset == "off":
        lua = "-- Auto-generated by AruShell Animation Customizer (off)\nhl.config({ animations = { enabled = false } })\n"
        batch = ["keyword animations:enabled 0"]
    else:
        bezier_def, d_win, d_out, d_fade, d_ws, d_layer = CURVES.get(preset, CURVES["smooth"])
        cname = bezier_def.split(",")[0].strip()
        s_win = round(d_win * speed, 2)
        s_out = round(d_out * speed, 2)
        s_fade = round(d_fade * speed, 2)
        s_ws = round(d_ws * speed, 2)
        s_layer = round(d_layer * speed, 2)
        lua = f"""-- Auto-generated by AruShell Animation Customizer ({preset}, {win_style}, {ws_style}, {speed}x)
hl.config({{
    animations = {{
        enabled = true,
        bezier = {{
            "{bezier_def}"
        }},
        animation = {{
            "windows, 1, {s_win}, {cname}, {win_in_arg}",
            "windowsOut, 1, {s_out}, {cname}, {win_out_arg}",
            "fade, 1, {s_fade}, {cname}",
            "workspaces, 1, {s_ws}, {cname}, {ws_style}",
            "layers, 1, {s_layer}, {cname}, fade"
        }}
    }}
}})
"""
        batch = [
            "keyword animations:enabled 1",
            f"keyword bezier {bezier_def}",
            f"keyword animation windows, 1, {s_win}, {cname}, {win_in_arg}",
            f"keyword animation windowsOut, 1, {s_out}, {cname}, {win_out_arg}",
            f"keyword animation fade, 1, {s_fade}, {cname}",
            f"keyword animation workspaces, 1, {s_ws}, {cname}, {ws_style}",
            f"keyword animation layers, 1, {s_layer}, {cname}, fade",
        ]

    os.makedirs(os.path.dirname(ANIM_LUA), exist_ok=True)
    with open(ANIM_LUA, "w", encoding="utf-8") as f:
        f.write(lua)

    sig = find_hypr_sig()
    if not sig:
        return 0
    env = os.environ.copy()
    env["HYPRLAND_INSTANCE_SIGNATURE"] = sig

    eval_code = " ".join(l.strip() for l in lua.splitlines() if l.strip() and not l.strip().startswith("--"))
    res = subprocess.run(
        ["hyprctl", "eval", eval_code],
        env=env,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    if res.returncode != 0:
        subprocess.run(
            ["hyprctl", "--batch", "; ".join(batch)],
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
